import { test, expect } from '@playwright/test';

test('complete a fresh game, restore progress, and confirm a reset', async ({page})=>{
  const errors: string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{level:1})).toContainText('Комната');
  await page.locator('[data-place="letter"]').click();
  await page.getByRole('button',{name:'Взять письмо'}).click();
  await page.getByRole('button',{name:'Письмо',exact:true}).click();
  await page.locator('[data-place="candle"]').click();
  await expect(page.getByRole('status')).toContainText('Сначала зажгите свечу');
  await page.getByRole('button',{name:'Письмо',exact:true}).click();
  await page.locator('[data-place="plant"]').click();
  await page.getByRole('button',{name:'Взять спички'}).click();
  await page.getByRole('button',{name:'Спички',exact:true}).click();
  await page.locator('[data-place="candle"]').click();
  await page.getByRole('button',{name:'Письмо',exact:true}).click();
  await page.locator('[data-place="candle"]').click();
  await expect(page.getByRole('dialog')).toContainText('Короткая ищет птицу');
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await expect(page.locator('#progress-count')).toHaveText('1 / 4');
  await page.locator('[data-place="clock"]').click();
  await page.getByRole('combobox',{name:'Часы',exact:true}).selectOption('4');
  await page.getByRole('combobox',{name:'Минуты',exact:true}).selectOption('40');
  await page.getByRole('button',{name:'Перевести стрелки'}).click();
  await expect(page.getByRole('status')).toContainText('Тиканье не вернулось');
  await page.getByRole('combobox',{name:'Минуты',exact:true}).selectOption('45');
  await page.getByRole('button',{name:'Перевести стрелки'}).click();
  await page.getByRole('button',{name:'Забрать ключ'}).click();
  await page.getByRole('button',{name:'Маленький ключ',exact:true}).click();
  await page.locator('[data-place="drawer"]').click();
  await page.getByRole('button',{name:'Взять: Кассета'}).click();
  await page.getByRole('button',{name:'Взять: Фотография'}).click();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Фотография',exact:true}).click();
  await page.locator('[data-place="mirror"]').click();
  await expect(page.getByRole('dialog')).toContainText('96.4 FM');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Кассета',exact:true}).click();
  await page.locator('[data-place="radio"]').click();
  await page.getByRole('button',{name:'Слушать запись'}).click();
  await expect(page.getByRole('status')).toContainText('Нужна точная частота');
  await page.getByRole('slider').fill('964');
  await page.getByRole('button',{name:'Слушать запись'}).click();
  await expect(page.getByRole('dialog')).toContainText('Дождь стучал трижды');
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('#progress-count')).toHaveText('3 / 4');
  await page.getByRole('button',{name:'Мой дневник'}).click();
  await expect(page.getByRole('dialog')).toContainText('Голос дома');
  await page.keyboard.press('Escape');
  await page.locator('[data-place="door"]').click();
  await page.getByRole('button',{name:'Постучать и открыть'}).click();
  await expect(page.getByRole('status')).toContainText('Стук затих');
  for(const [index,count] of [[0,2],[1,1],[2,3]])for(let i=0;i<count;i++)await page.locator(`[data-digit="${index}"]`).click();
  await page.getByRole('button',{name:'Постучать и открыть'}).click();
  await expect(page.getByRole('heading',{name:'Вы вспомнили дорогу.'})).toBeVisible();
  await expect(page.locator('#progress-count')).toHaveText('4 / 4');
  await page.reload();
  await expect(page.locator('#progress-count')).toHaveText('4 / 4');
  await page.getByRole('button',{name:'Начать заново',exact:true}).click();
  await page.getByRole('button',{name:'Остаться здесь'}).click();
  await expect(page.locator('#progress-count')).toHaveText('4 / 4');
  await page.getByRole('button',{name:'Начать заново',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Начать заново',exact:true}).click();
  await expect(page.locator('#progress-count')).toHaveText('0 / 4');
  await expect(page.locator('.inventory-item')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('mobile layout, progressive hints, keyboard dialog and sound toggle',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.getByRole('button',{name:'Нужна подсказка?'}).click();
  await expect(page.locator('#hint-counter')).toHaveText('1 / 3');
  await page.getByRole('button',{name:'Нужна подсказка?'}).click();
  await page.getByRole('button',{name:'Нужна подсказка?'}).click();
  await expect(page.locator('#hint-text')).toContainText('спички');
  await page.getByRole('button',{name:'Как играть',exact:true}).click();
  await page.keyboard.press('Shift+Tab');
  await expect(page.getByRole('button',{name:'Я готов вспомнить'})).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button',{name:'Закрыть',exact:true})).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'Включить звук',exact:true}).click();
  await expect(page.getByRole('button',{name:'Выключить звук',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Выключить звук',exact:true}).click();
  await expect(page.getByRole('button',{name:'Включить звук',exact:true})).toHaveAttribute('aria-pressed','false');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});

test('corrupt or unavailable storage does not prevent playing',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('quiet-hour:v1','broken'));
  await page.goto('/');
  await expect(page.locator('#progress-count')).toHaveText('0 / 4');
  await page.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('blocked');}});});
  await page.reload();
  await page.locator('[data-place="letter"]').click();
  await page.getByRole('button',{name:'Взять письмо'}).click();
  await expect(page.getByRole('button',{name:'Письмо',exact:true})).toBeVisible();
  await expect(page.locator('#save-status')).toContainText('НЕДОСТУПНО');
});
